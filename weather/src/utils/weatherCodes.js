export function getWeatherInfo(code) {
  if (code === undefined || code === null || !(code in WEATHER_CODES)) {
    return {
      label: 'Partly Cloudy',
      condition: WEATHER_CONDITIONS.PARTLY_CLOUDY,
      icon: 'CloudSun',
      tips: 'Variable weather. Check real-time forecasts before heading out.',
      outfit: 'Flexible light layering and comfortable footwear.',
      activity: 'General outdoor and indoor activities.',
    };
  }
  return WEATHER_CODES[code];
}
